"""Нормализация казахского текста перед подсчётом WER.

Без нормализации метрика меряет не распознавание, а пунктуацию и регистр:
модель, написавшая «сәлем» вместо «Сәлем,», получила бы ошибку на ровном месте.
Это стандартная практика в оценке ASR, но для казахского есть две своих детали.

Первая — буквы, которых нет в русском: ә, ғ, қ, ң, ө, ұ, ү, h, і. Их нельзя
трогать заменами «похожих» символов, иначе метрика начнёт прощать настоящие
ошибки распознавания.

Вторая — гомоглифы. Казахская «і» (U+0456) и русская «и», а также латинские
a, e, o, c, p, x визуально совпадают с кириллическими. Whisper при обучении на
многоязычных данных иногда выдаёт латинский символ вместо кириллического, и без
приведения это считалось бы ошибкой распознавания, хотя произнесено верно.
"""

from __future__ import annotations

import re
import unicodedata

# Латиница -> кириллица для визуально совпадающих символов.
# Обратное направление недопустимо: казахские буквы уникальны и трогать их нельзя.
_HOMOGLYPHS = str.maketrans({
    "a": "а", "A": "А",
    "e": "е", "E": "Е",
    "o": "о", "O": "О",
    "c": "с", "C": "С",
    "p": "р", "P": "Р",
    "x": "х", "X": "Х",
    "y": "у", "Y": "У",
    "k": "к", "K": "К",
    "M": "М", "H": "Н", "B": "В", "T": "Т",
})

# Пунктуация и любые непечатные символы. Дефис внутри слова сохраняем:
# в казахском он несёт смысл (қаза-қазан), а между словами — разделитель.
_PUNCT_RE = re.compile(r"[^\w\s\-Ѐ-ӿ]", re.UNICODE)
_SPACE_RE = re.compile(r"\s+")
_EDGE_HYPHEN_RE = re.compile(r"(?<!\w)-|-(?!\w)")


def normalize(text: str) -> str:
    """Приводит строку к виду, на котором честно считается WER."""
    if not text:
        return ""

    # NFC: казахские буквы должны быть одной кодовой точкой, а не «буква + диакритика»,
    # иначе одинаковые на вид строки окажутся разными.
    text = unicodedata.normalize("NFC", text)
    text = text.translate(_HOMOGLYPHS)
    text = text.lower()
    text = _PUNCT_RE.sub(" ", text)
    text = _EDGE_HYPHEN_RE.sub(" ", text)
    text = _SPACE_RE.sub(" ", text)
    return text.strip()


def words(text: str) -> list[str]:
    normalized = normalize(text)
    return normalized.split() if normalized else []


def characters(text: str) -> list[str]:
    """Символы без пробелов: CER считается по ним."""
    return [char for char in normalize(text) if not char.isspace()]
